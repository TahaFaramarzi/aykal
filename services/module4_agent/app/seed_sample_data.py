def seed_catalog() -> int:
    """
    Stores the sample catalog in kb_chunks (replacing the old one).
    """

    chunks = chunk_text(CATALOG_TEXT)
    embeddings = embed_texts(chunks)

    with get_db() as cur:
        cur.execute(
            "DELETE FROM kb_chunks WHERE source = %s",
            (SOURCE,)
        )

        for content, embedding in zip(chunks, embeddings):
            cur.execute(
                """
                INSERT INTO kb_chunks (source, content, embedding)
                VALUES (%s, %s, %s)
                """,
                (SOURCE, content, Json(embedding))
            )

    return len(chunks)


def seed_eval_questions() -> int:
    """
    Stores the evaluation questions (skips ones that already exist).
    """

    added = 0

    with get_db() as cur:
        for question, expected in EVAL_QUESTIONS:
            cur.execute(
                """
                INSERT INTO eval_questions (question, expected_answer)
                SELECT %s, %s
                WHERE NOT EXISTS (
                    SELECT 1 FROM eval_questions WHERE question = %s
                )
                """,
                (question, expected, question)
            )
            added += cur.rowcount

    return added


if __name__ == "__main__":
    init_kb_table()

    chunk_count = seed_catalog()
    print(f"Catalog stored: {chunk_count} chunks (source: {SOURCE})")

    added = seed_eval_questions()
    print(f"Evaluation questions added: {added} of {len(EVAL_QUESTIONS)}")